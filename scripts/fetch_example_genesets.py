"""Freeze example gene sets from MyGeneset into src/amigo3/example_genesets.yaml.

Examples are expression-derived MSigDB signatures (Hallmark, C8 cell types, C2
chemical/genetic perturbations), not GO-derived sets, so GO enrichment says
something independent of how the set was made. MSigDB gene sets are CC BY 4.0;
KEGG and BioCarta subsets, which carry other terms, are not used.

Each example also carries the GO terms its curated interpretation expects, from
the genesets curation corpus (monarch-initiative/genesets, curation/genesets).
Members keep the identifiers MyGeneset publishes; mapping onto the loaded gene
catalog happens at request time, against the pinned build.

    uv run python scripts/fetch_example_genesets.py --interpretations ../genesets/curation/genesets
"""

from __future__ import annotations

import argparse
import datetime
import subprocess
from pathlib import Path

import httpx
import yaml

API = "https://mygeneset.info/v1"
EXAMPLES = (
    "HALLMARK_INTERFERON_GAMMA_RESPONSE",
    "HALLMARK_G2M_CHECKPOINT",
    "HALLMARK_HYPOXIA",
    "HALLMARK_EPITHELIAL_MESENCHYMAL_TRANSITION",
    "TRAVAGLINI_LUNG_CILIATED_CELL",
    "MURARO_PANCREAS_BETA_CELL",
    "HAY_BONE_MARROW_NEUTROPHIL",
    "DESCARTES_FETAL_CEREBRUM_EXCITATORY_NEURONS",
    "SANA_RESPONSE_TO_IFNG_UP",
    "DANG_MYC_TARGETS_UP",
    "FRASOR_RESPONSE_TO_ESTRADIOL_UP",
)
MEMBER_FIELDS = ("symbol", "source_id", "ncbigene", "uniprot", "ensemblgene")
MSIGDB_FIELDS = ("category", "subcategory", "systematic_name", "contributor", "pmid", "url")
OUTPUT = Path(__file__).resolve().parents[1] / "src/amigo3/example_genesets.yaml"


def expected_terms(directory: Path, identifier: str) -> list[dict]:
    document = yaml.safe_load((directory / f"{identifier}.yaml").read_text())
    return [
        {
            "id": a["term"]["id"],
            "label": a["term"]["label"],
            "category": a.get("category", ""),
            "confidence": a.get("confidence", ""),
        }
        for a in document.get("associations") or []
        if a["term"]["id"].startswith("GO:")
    ]


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument(
        "--interpretations", type=Path, required=True, help="genesets curation/genesets directory"
    )
    args = parser.parse_args()
    commit = subprocess.run(
        ["git", "-C", str(args.interpretations), "rev-parse", "--short", "HEAD"],
        capture_output=True,
        text=True,
        check=True,
    ).stdout.strip()
    with httpx.Client(base_url=API, timeout=30) as client:
        metadata = client.get("/metadata").raise_for_status().json()
        sets = []
        for identifier in EXAMPLES:
            doc = client.get(f"/geneset/{identifier}").raise_for_status().json()
            genes = doc.get("genes") or []
            genes = genes if isinstance(genes, list) else [genes]
            msigdb = doc.get("msigdb") or {}
            sets.append(
                {
                    "_id": doc["_id"],
                    "name": doc.get("name"),
                    "description": doc.get("description") or "",
                    "source": doc["source"],
                    "taxid": doc["taxid"],
                    "count": doc.get("count"),
                    "msigdb": {k: msigdb[k] for k in MSIGDB_FIELDS if msigdb.get(k)},
                    "expected_go": expected_terms(args.interpretations, identifier),
                    "genes": [{k: g[k] for k in MEMBER_FIELDS if g.get(k)} for g in genes],
                }
            )
    sources = sorted({s["source"] for s in sets})
    document = {
        "provenance": {
            "service": API,
            "retrieved": datetime.date.today().isoformat(),
            "source_versions": {s: metadata["src"][s].get("version") for s in sources},
            "license": "MSigDB gene sets: CC BY 4.0 (https://www.gsea-msigdb.org/gsea/msigdb_license_terms.jsp)",
            "expected_go": f"monarch-initiative/genesets curation/genesets at {commit}",
            "script": "scripts/fetch_example_genesets.py",
        },
        "genesets": sets,
    }
    OUTPUT.write_text(
        "# Generated by scripts/fetch_example_genesets.py from MyGeneset. Do not edit by hand.\n"
        + yaml.safe_dump(document, sort_keys=False, allow_unicode=True, width=100)
    )
    print(f"Wrote {len(sets)} gene sets to {OUTPUT}")


if __name__ == "__main__":
    main()
